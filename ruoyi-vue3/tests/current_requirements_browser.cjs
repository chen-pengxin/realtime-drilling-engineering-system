    assert((await page.locator('.pose-workspace').innerText()).includes('MODEL_NOT_CONFIGURED'))
    await screenshot('prediction');record('prediction keeps a hierarchical wellbore input and empty model results')
    await navigate('/drilling/basic/catalog');await page.locator('.library-tree-panel .el-tree-node__label,.library-tree-panel .tree-node').first().waitFor()
    await page.waitForTimeout(600);await screenshot('catalog')
    // Open the existing source library entry point; this tests the actual import-review dialog without uploading or saving data.
    await page.evaluate(()=>document.querySelector('.library-page').__vueParentComponent.refs.sourceReviewLibrary.show())
    const library=page.getByRole('dialog',{name:'来源资料库',exact:true});await library.waitFor();await library.getByRole('button',{name:'核对资料',exact:true}).first().click()
