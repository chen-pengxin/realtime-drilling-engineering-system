    const multi=review.locator('.wellbore-select');await multi.getByRole('button',{name:'清空',exact:true}).click()
    const modelValues=()=>multi.evaluate(el=>{let c=el.__vueParentComponent;while(c&&!c.type.__file?.endsWith('/WellboreSelect.vue'))c=c.parent;return c?.props.modelValue})
    assert.deepEqual(await modelValues(),[]);await multi.locator('.el-select').click()
