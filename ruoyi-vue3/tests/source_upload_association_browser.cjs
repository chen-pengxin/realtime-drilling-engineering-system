// Uses an isolated backend; creates source files but no calculation versions.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright')
const base=process.env.DRILLING_FRONTEND_URL||'http://127.0.0.1:15173'
assert(process.env.DRILLING_QA_ALLOW_MUTATION==='1' && base.includes(':15173'),'Use the isolated frontend and disposable QA database')
const session=process.env.DRILLING_SESSION_ID
assert(session,'Provide a QA session')
const out=path.resolve(process.env.DRILLING_BROWSER_REPORT||'artifacts/source-upload-association');fs.mkdirSync(out,{recursive:true})
const checks=[],errors=[],responseChecks=[],requestPaths=[];const record=name=>{checks.push(name);console.log('PASS '+name)}
;(async()=>{
const browser=await chromium.launch({headless:true,...(process.env.DRILLING_BROWSER_EXECUTABLE?{executablePath:process.env.DRILLING_BROWSER_EXECUTABLE}:{})})
try{
  const context=await browser.newContext({viewport:{width:1600,height:1050}})
  await context.addCookies([{name:'JSESSIONID',value:session,url:base},{name:'Admin-Token',value:'shiro-session',url:base}])
  const page=await context.newPage();page.setDefaultTimeout(20000);page.on('pageerror',error=>errors.push(String(error)))
  page.on('request',request=>requestPaths.push(new URL(request.url()).pathname))
  page.on('response',response=>{if(response.url().includes('/api/'))responseChecks.push((async()=>{if(response.status()>=400)errors.push(`${response.status()} ${new URL(response.url()).pathname}`);else if((response.headers()['content-type']||'').includes('json')){const payload=await response.json().catch(()=>null);if(typeof payload?.code==='number'&&![0,200].includes(payload.code))errors.push(`${payload.code} ${new URL(response.url()).pathname}: ${payload.msg}`)}})())})
  await page.addInitScript(()=>localStorage.setItem('drilling.fieldId','13'))
  await page.goto(base+'/drilling/basic/catalog',{waitUntil:'domcontentloaded'})
  const engineeringConfirmation=page.getByRole('dialog',{name:'确认工程评价配置',exact:true})
  if(await engineeringConfirmation.waitFor({state:'visible',timeout:6000}).then(()=>true,()=>false)){
    await engineeringConfirmation.locator('.confirm-summary').waitFor()
    await engineeringConfirmation.locator('.el-checkbox__label').click()
    await engineeringConfirmation.getByRole('button',{name:'确认配置',exact:true}).click()
    await engineeringConfirmation.waitFor({state:'hidden'})
  }
  const tree=page.locator('.library-tree-panel')
  const field=tree.getByText('测试案例 A',{exact:true}).locator('xpath=ancestor::*[contains(concat(" ", normalize-space(@class), " "), " el-tree-node ")][1]')
  await field.getByText('主井眼',{exact:true}).first().click()
  await page.getByRole('button',{name:'导入来源文件',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'导入来源文件',exact:true})
  await dialog.waitFor()
  const defaultPath=await dialog.locator('.engineering-path').innerText()
  assert.match(defaultPath,/测试.*\/.*测试案例 A.*\/.*井1.*\/.*主井眼/)
  assert.equal(defaultPath.split(' / ').length,4)
  record('选择文件前即可看到区块—井场—井—井眼完整关联层级')
  const name='浏览器关联验证-'+Date.now()+'.csv'
  await dialog.locator('input[type=file]').setInputFiles({name,mimeType:'text/csv',buffer:Buffer.from('MD,Inc,Azi\n0,10,20\n30,12,22\n60,15,'+(25+Math.random()).toFixed(8)+'\n')})
  const row=dialog.getByRole('row').filter({hasText:name})
  assert.match(await row.locator('.row-path').innerText(),/井1.*主井眼/)
  await dialog.getByRole('button',{name:'上传并关联',exact:true}).click()
  await dialog.getByText('请选择设计方案或实钻测斜',{exact:true}).waitFor()
  record('轨迹用途未选时在本地提示，不上传并猜测用途')
  await row.locator('.el-select').nth(2).click()
  await page.getByRole('option',{name:'实钻测斜',exact:true}).click()
  await dialog.getByRole('button',{name:'上传并关联',exact:true}).click()
  await row.getByText('已关联入库',{exact:true}).waitFor({timeout:60000})
  await page.screenshot({path:path.join(out,'upload-association.png'),fullPage:true,animations:'disabled',mask:[page.locator('.avatar-container')]})
  record('文件列表保持可见关联路径、文件用途和实钻用途，真实上传成功')
  await dialog.getByRole('button',{name:'完成',exact:true}).click()
  const review=page.getByRole('dialog',{name:'来源资料确认',exact:true});await review.waitFor()
  await review.getByText('已关联层级',{exact:true}).waitFor()
  assert.match(await review.innerText(),/测试案例 A.*井1.*主井眼/)
  record('来源核对弹窗读取后端保存的关联对象')
  await review.getByRole('button',{name:'取 消',exact:true}).click()
  await page.getByRole('columnheader',{name:'工程层级',exact:true}).waitFor()
  await page.getByRole('row').filter({hasText:name}).first().waitFor()
  record('资料文件页展示已入库文件及工程层级')
  await page.getByRole('tab',{name:'轨迹数据版本',exact:true}).click()
  await page.getByRole('button',{name:'导入实钻版本',exact:true}).click()
  const version=page.getByRole('dialog',{name:'导入轨迹版本',exact:true});await version.waitFor()
  const target=version.locator('.el-form-item').filter({has:page.getByText('关联层级',{exact:true})})
  assert.match(await target.innerText(),/测试案例 A.*井1.*主井眼/)
  await version.locator('.el-dialog__footer').waitFor()
  await page.waitForFunction(()=>{const el=document.querySelector('[aria-label="导入轨迹版本"]');return el&&getComputedStyle(el).opacity==='1'&&!el.getAnimations().some(a=>a.playState==='running')})
  await page.screenshot({path:path.join(out,'trajectory-version-target.png'),fullPage:true,animations:'disabled',mask:[page.locator('.avatar-container')]})
  const reviewsBefore=requestPaths.filter(path=>/\/sources\/\d+\/review$/.test(path)).length
  const libraryResponse=page.waitForResponse(response=>/\/sources\?/.test(response.url())&&response.request().method()==='GET')
  await version.getByRole('button',{name:'从资料库选择',exact:true}).click()
  const sourceList=await(await libraryResponse).json()
  const library=page.getByRole('dialog',{name:'来源资料库',exact:true});await library.getByRole('columnheader',{name:'资料状态',exact:true}).waitFor()
  assert(sourceList.rows.every(row=>['PENDING','CONFIRMED','REJECTED'].includes(row.review_status)))
  assert.equal(requestPaths.filter(path=>/\/sources\/\d+\/review$/.test(path)).length,reviewsBefore)
  await library.locator('.el-dialog__headerbtn').click()
  record('来源资料库一次读取确认状态，打开列表不逐项发起核对请求')
  await version.getByRole('button',{name:'取 消',exact:true}).click()
  record('轨迹版本导入在选择文件前显示完整井眼归属')
  await page.getByRole('tab',{name:'资料文件',exact:true}).click()
  await page.getByRole('button',{name:'导入来源文件',exact:true}).click()
  await dialog.waitFor()
  // Exercise the real tree dropdown without assigning a file to a guessed bore.
  await dialog.locator('.target-select').click()
  await page.getByRole('tree').last().getByText('井2',{exact:true}).waitFor()
  record('上传目标使用工程树选择，包含上级层级')
  await page.keyboard.press('Escape')
  await page.setViewportSize({width:430,height:932})
  await dialog.locator('.target-select').waitFor()
  await page.screenshot({path:path.join(out,'upload-mobile.png'),fullPage:true,animations:'disabled',mask:[page.locator('.avatar-container')]})
  await Promise.all(responseChecks)
  assert.equal(errors.length,0,errors.join('\n'))
  record('桌面和窄屏显示无脚本异常')
  fs.writeFileSync(path.join(out,'results.json'),JSON.stringify({passed:true,checks,errors},null,2))
}finally{await browser.close()}
})().catch(error=>{console.error(error);fs.writeFileSync(path.join(out,'results.json'),JSON.stringify({passed:false,checks,errors,error:String(error)},null,2));process.exitCode=1})
