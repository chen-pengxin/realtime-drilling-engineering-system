/* Run with GPU_QA_CONFIG pointing to credentials and fixtures in an isolated QA schema. */
const fs = require('fs')
const path = require('path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const config = JSON.parse(fs.readFileSync(process.env.GPU_QA_CONFIG, 'utf8'))
if (!/^drilling_ops_qa_gpu_[0-9]+$/.test(config.database)) throw Error('Isolated GPU/UI QA schema required')
const base = process.env.ACCESS_QA_FRONTEND || 'http://127.0.0.1:15173'
const out = path.resolve(__dirname, '../../artifacts/gpu-drilling-ui')
fs.mkdirSync(out, { recursive: true })
const checks = [], errors = [], serverErrors = []
function check(value, name) { checks.push({ name, passed: Boolean(value) }); if (!value) throw Error(name); console.log('PASS', name) }
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.ACCESS_QA_BROWSER, args: ['--enable-webgl', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
  const ctx = await browser.newContext({ viewport: { width: 1600, height: 1000 } })
  const page = await ctx.newPage()
  page.on('pageerror', e => errors.push(String(e)))
  page.on('response', r => { if (r.status() >= 500 && r.url().includes('/prod-api')) serverErrors.push(r.url()) })
  const login = await ctx.request.post(base + '/prod-api/login', { form: { username: 'admin', password: config.adminPassword, rememberMe: 'false' }, headers: { 'X-Requested-With': 'XMLHttpRequest' } })
  check([0, 200].includes((await login.json()).code), 'QA account login')
  await ctx.addCookies([{ name: 'Admin-Token', value: 'shiro-session', url: base }])
  await page.addInitScript(id => localStorage.setItem('drilling.fieldId', id), String(config.fixture.fieldId))
  const routes = [
    ['/drilling/realtime', 'realtime'], ['/drilling/tasks/anticollision', 'anticollision'],
    ['/drilling/tasks/prediction/overview', 'prediction'], ['/drilling/tasks/prediction/models', 'models'],
    ['/drilling/tasks/replanning', 'replanning'], ['/drilling/basic/catalog', 'catalog'],
    ['/drilling/basic/surveys', 'surveys'], ['/drilling/basic/realtime-data', 'ingest'],
    ['/drilling/basic/config', 'config'], ['/drilling/basic/files', 'files']
  ]
  async function visit(route) { await page.goto(base + route); await page.locator('.drilling-page-frame').waitFor(); await page.waitForTimeout(700) }
  async function shot(name) { await page.screenshot({ path: path.join(out, name + '.png'), fullPage: true }) }
  async function width(name) { check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 3), name + ' fits viewport') }
  for (const [route, name] of routes) {
    await visit(route)
    check(await page.locator('.sidebar-container').getByText('钻井工程', { exact: true }).count() === 1, name + ' single drilling menu')
    check(await page.locator('.drilling-page-frame .screen-header').count() === 0, name + ' no repeated branded header')
    await width(name + ' desktop')
    await shot(name + '-desktop')
  }
  // Preserve real task interactions and real trajectory output.
  await visit('/drilling/tasks/anticollision')
  await page.locator('.constraint-panel .el-select__wrapper').first().click()
  await page.getByRole('option', { name: 'RT-001 · 正钻井', exact: true }).click()
  const scanned = page.waitForResponse(r => r.url().includes('/anti-collision/network-scan') && r.request().method() === 'POST', { timeout: 90000 })
  await page.getByRole('button', { name: '执行防碰扫描', exact: true }).click()
  check((await scanned.catch(async e=>{await shot('scan-failure');console.error('SCAN DIAGNOSTICS',await page.locator('.constraint-panel').innerText(),await page.locator('.el-message').allTextContents(),errors,serverErrors);throw e})).ok(), 'real full-neighbor scan succeeds')
  await page.locator('.scene-wrap canvas').waitFor()
  check(await page.getByRole('tab', { name: '3D 视图', exact: true }).getAttribute('aria-selected') === 'true', 'anti-collision opens in 3D')
  await shot('anticollision-3d')
  await page.getByRole('tab', { name: '2D 视图', exact: true }).click()
  await page.locator('.projection-chart canvas').first().waitFor()
  check(await page.locator('.projection-chart canvas').count() === 2, 'two anti-collision projections render')
  await shot('anticollision-2d')
  await page.getByRole('tab', { name: '防碰扫描结果', exact: true }).click()
  check(await page.getByText('全井网井间关系与风险井段', { exact: true }).isVisible(), 'well relations and risk segments retained')
  await shot('anticollision-results')
  // Hierarchical management and normal dialogs.
  await visit('/drilling/basic/catalog')
  check(await page.locator('.drilling-field-search').count() === 0, 'catalog has no unrelated field selector')
  await page.getByRole('row').filter({ hasText: '页面验收区块' }).getByRole('button', { name: '管理井场', exact: true }).click()
  await page.getByRole('row').filter({ hasText: '页面验收井场' }).getByRole('button', { name: '管理井', exact: true }).click()
  await page.getByRole('cell', { name: '页面验收井', exact: true }).waitFor()
  check(true, 'block to field to well management retained')
  await visit('/drilling/basic/surveys')
  check(await page.getByRole('dialog').count() === 0, 'well editor stays closed until requested')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  await page.getByRole('dialog', { name: '新增井', exact: true }).waitFor()
  await shot('well-dialog-desktop')
  await page.getByRole('button', { name: '取 消', exact: true }).click()
  await visit('/drilling/basic/config')
  for (const label of ['坐标与测量', '防碰评价与误差模型', '风险阈值', '轨迹再规划', '实时姿态预测与报警']) {
    await page.getByRole('tab', { name: label, exact: true }).click()
    check(await page.getByRole('tabpanel').filter({ visible: true }).count() === 1, 'configuration group ' + label)
  }
  await visit('/drilling/basic/files')
  await page.getByRole('cell', { name: '测斜数据.csv', exact: true }).waitFor()
  check(await page.getByRole('cell', { name: '测斜', exact: true }).count() > 0, 'file category has Chinese label')
  await page.getByRole('tab', { name: '井场审计记录', exact: true }).click()
  check(await page.getByRole('columnheader', { name: '动作', exact: true }).isVisible(), 'audit list on its own tab')
  await visit('/drilling/tasks/prediction/overview')
  check(await page.getByText('尚未启用预测模型', { exact: true }).isVisible(), 'unconfigured model remains explicit')
  await page.getByRole('tab', { name: '预测轨迹表', exact: true }).click()
  check(await page.getByText('未生成预测结果', { exact: true }).isVisible(), 'no fabricated model predictions')
  await visit('/drilling/tasks/prediction/models')
  await page.getByRole('button', { name: '设置增量更新参数', exact: true }).click()
  await page.getByRole('dialog', { name: '自动增量更新设置', exact: true }).waitFor()
  await shot('incremental-settings-desktop')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  // Theme switches affect canvas and forms without a reload.
  await visit('/drilling/tasks/replanning')
  await page.getByRole('tab', { name: '二维视图', exact: true }).click()
  await page.locator('.projection-chart canvas').first().waitFor()
  await page.evaluate(() => document.documentElement.classList.remove('dark'))
  await page.waitForTimeout(350)
  check(await page.locator('.workspace').evaluate(el => getComputedStyle(el).backgroundColor) === 'rgb(255, 255, 255)', 'replanning uses light theme background')
  check(await page.locator('.target-coordinates input').count() === 3, 'target coordinates have separate labeled inputs')
  await page.locator('.target-coordinates input').first().fill('12345.67')
  await page.locator('.target-coordinates input').first().press('Tab')
  check(await page.locator('.target-coordinates input').first().inputValue() === '12345.67', 'full target coordinate remains editable')
  await shot('replanning-light')
  await page.getByRole('tab', { name: '三维视图', exact: true }).click()
  await page.locator('.scene-board canvas').waitFor()
  await shot('replanning-3d-light')
  await page.evaluate(() => document.documentElement.classList.add('dark'))
  await page.waitForTimeout(250)
  await shot('replanning-3d-dark')
  // Real hardware first, then deterministic NVIDIA and unavailable snapshots for display coverage.
  await page.goto(base + '/operations/monitor')
  await page.locator('.gpu-sources').waitFor()
  await page.getByRole('cell', { name: 'Apple M5', exact: true }).first().waitFor({ timeout: 25000 })
  check(true, 'real Apple GPU reaches operations monitor through Java')
  await shot('gpu-actual-hardware')
  const current = await (await ctx.request.get(base + '/prod-api/api/operations/monitor')).json()
  await page.route('**/prod-api/api/operations/monitor', route => route.fulfill({ json: { ...current, data: { ...current.data, gpu: { business: { status: 'NO_DEVICE', devices: [] }, algorithm: { status: 'UP', devices: [{ name: 'NVIDIA RTX A6000', vendor: 'NVIDIA', status: 'UP', utilization_percent: 73, memory_used_mb: 2048, memory_total_mb: 49140, temperature_c: 61, power_w: 198.5, driver_version: '550.54' }] } } } } }))
  await page.getByRole('button', { name: '刷新', exact: true }).click()
  await page.getByRole('cell', { name: 'NVIDIA RTX A6000', exact: true }).waitFor()
  check(await page.getByRole('cell', { name: '73%', exact: true }).isVisible(), 'NVIDIA utilization visible')
  check(await page.getByRole('cell', { name: '61 °C', exact: true }).isVisible(), 'GPU temperature visible')
  await shot('gpu-nvidia-fixture')
  await page.unroute('**/prod-api/api/operations/monitor')
  // All drilling routes must remain usable at phone width.
  await page.setViewportSize({ width: 390, height: 844 })
  for (const [route, name] of routes) { await visit(route); await width(name + ' mobile'); await shot(name + '-mobile') }
  await visit('/drilling/basic/surveys')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新增井', exact: true })
  await dialog.waitFor(); await page.waitForTimeout(300)
  const box = await dialog.boundingBox()
  check(box.x >= 0 && box.x + box.width <= 393, 'mobile well dialog fits viewport')
  await shot('well-dialog-mobile')
  check(!errors.length, 'no browser page errors: ' + errors.join(';'))
  check(!serverErrors.length, 'no backend 500 responses')
  fs.writeFileSync(path.join(out, 'browser-results.json'), JSON.stringify({ passed: checks.length, checks, errors, serverErrors }, null, 2))
  await browser.close()
})().catch(error => { console.error(error); process.exit(1) })
