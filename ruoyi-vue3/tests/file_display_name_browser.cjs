// Exercise original filenames and editable display labels on disposable QA services.
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.DRILLING_FRONTEND_URL || 'http://127.0.0.1:15173'
assert(process.env.DRILLING_QA_ALLOW_MUTATION === '1' && base.includes(':15173'))
const session = process.env.DRILLING_SESSION_ID; assert(session)
const out = path.resolve(process.env.DRILLING_BROWSER_REPORT || 'artifacts/file-display-name')
fs.mkdirSync(out, { recursive: true })
const checks = [], errors = [], pending = []
const record = name => { checks.push(name); console.log('PASS ' + name) }
;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.DRILLING_BROWSER_EXECUTABLE ? { executablePath: process.env.DRILLING_BROWSER_EXECUTABLE } : {}) })
  try {
    const context = await browser.newContext({ viewport: { width: 1680, height: 1050 }, acceptDownloads: true })
    await context.addCookies([{ name: 'JSESSIONID', value: session, url: base }, { name: 'Admin-Token', value: 'shiro-session', url: base }])
    const page = await context.newPage(); page.setDefaultTimeout(20000)
    page.on('pageerror', error => errors.push(String(error)))
    page.on('response', response => {
      if (!response.url().includes('/api/')) return
      pending.push((async () => {
        if (response.status() >= 400) errors.push(`${response.status()} ${new URL(response.url()).pathname}`)
        else if ((response.headers()['content-type'] || '').includes('json')) {
          const data = await response.json().catch(() => null)
          if (typeof data?.code === 'number' && ![0, 200].includes(data.code)) errors.push(`${data.code} ${new URL(response.url()).pathname}: ${data.msg}`)
        }
      })())
    })
    await page.addInitScript(() => localStorage.setItem('drilling.fieldId', '13'))
    await page.goto(base + '/drilling/basic/catalog', { waitUntil: 'domcontentloaded' })
    const confirmation = page.getByRole('dialog', { name: '确认工程评价配置', exact: true })
    if (await confirmation.waitFor({ state: 'visible', timeout: 6000 }).then(() => true, () => false)) {
      await confirmation.locator('.confirm-summary').waitFor()
      await confirmation.locator('.el-checkbox__label').click()
      await confirmation.getByRole('button', { name: '确认配置', exact: true }).click()
      await confirmation.waitFor({ state: 'hidden' })
    }
    const field = page.locator('.library-tree-panel').getByText('测试案例 A', { exact: true }).locator('xpath=ancestor::*[contains(concat(" ",normalize-space(@class)," ")," el-tree-node ")][1]')
    await field.getByText('主井眼', { exact: true }).first().click()
    await page.getByRole('columnheader', { name: '系统名称', exact: true }).waitFor()
    await page.getByRole('columnheader', { name: '原始文件名', exact: true }).waitFor()
    const nonce = String(Date.now())
    const raw = `Standard Survey Report (Actual) + 井1 [${nonce}] &.csv`, alias = `井1 实钻测斜资料 ${nonce}`, renamed = `井1 复测记录 ${nonce}`
    const bytes = Buffer.from(`MD,Inc,Azi\n0,10,20\n30,12,22\n60,15,25\n# ${nonce}\n`)
    const nextRaw = `Standard Survey Report (Re-survey) + 井1 [${nonce}].csv`, nextBytes = Buffer.concat([bytes, Buffer.from('# edition 2\n')])
    const review = page.getByRole('dialog', { name: '来源资料确认', exact: true })
    async function finish(dialog) {
      await dialog.getByRole('button', { name: '完成', exact: true }).click()
      await review.waitFor(); await review.getByRole('button', { name: '取 消', exact: true }).click()
    }
    async function download(button, name, content) {
      const awaiting = page.waitForEvent('download'); await button.click(); const file = await awaiting
      assert.equal(file.suggestedFilename(), name)
      const chunks = [], stream = await file.createReadStream()
      for await (const chunk of stream) chunks.push(chunk)
      assert(Buffer.concat(chunks).equals(content))
    }
    await page.getByRole('button', { name: '导入来源文件', exact: true }).click()
    const upload = page.getByRole('dialog', { name: '导入来源文件', exact: true })
    await upload.locator('input[type=file]').setInputFiles({ name: raw, mimeType: 'text/csv', buffer: bytes })
    let uploadRow = upload.getByRole('row').filter({ hasText: raw })
    await uploadRow.locator('td').nth(1).locator('input').fill(alias)
    await uploadRow.locator('.el-select').nth(2).click(); await page.getByRole('option', { name: '实钻测斜', exact: true }).click()
    await page.screenshot({ path: path.join(out, 'upload-names.png'), fullPage: true, animations: 'disabled', mask: [page.locator('.avatar-container')] })
    await upload.getByRole('button', { name: '上传并关联', exact: true }).click()
    await uploadRow.getByText('已关联入库', { exact: true }).waitFor({ timeout: 60000 }); await finish(upload)
    let row = page.getByRole('row').filter({ hasText: raw }).first(); await row.waitFor()
    await row.getByText(alias, { exact: true }).waitFor(); await row.getByText(raw, { exact: true }).waitFor()
    record('上传可分别填写系统名称，资料列表同时显示原始文件名')
    await row.getByRole('button', { name: '修改系统名称', exact: true }).click()
    const prompt = page.locator('.el-message-box'); await prompt.locator('input').fill(renamed)
    await prompt.getByRole('button', { name: '保存', exact: true }).click()
    row = page.getByRole('row').filter({ hasText: raw }).first(); await row.getByText(renamed, { exact: true }).waitFor()
    assert.match(await row.innerText(), /第 1 版/)
    await download(row.getByRole('button', { name: '原件', exact: true }), raw, bytes)
    record('修改系统名称后仍下载原始名称及原始字节，文件版次不变')
    await page.locator('.section-toolbar input[placeholder="系统名称或原始文件名"]').fill(renamed)
    await page.getByRole('button', { name: '查询', exact: true }).click()
    row = page.getByRole('row').filter({ hasText: raw }).first(); await row.waitFor()
    await row.getByRole('button', { name: '上传新版本', exact: true }).click()
    const update = page.getByRole('dialog', { name: '上传文件新版本', exact: true })
    await update.locator('input[type=file]').setInputFiles({ name: nextRaw, mimeType: 'text/csv', buffer: nextBytes })
    uploadRow = update.getByRole('row').filter({ hasText: nextRaw })
    assert.equal(await uploadRow.locator('td').nth(1).locator('input').inputValue(), renamed)
    await update.getByRole('button', { name: '保存新文件版本', exact: true }).click()
    await uploadRow.getByText('已保存第 2 版', { exact: true }).waitFor({ timeout: 60000 }); await finish(update)
    row = page.getByRole('row').filter({ hasText: nextRaw }).first(); await row.waitFor()
    await row.getByText(renamed, { exact: true }).waitFor()
    await download(row.getByRole('button', { name: '原件', exact: true }), nextRaw, nextBytes)
    record('新文件版次可沿用系统名称并保留该版实际上传的原名')
    await row.getByRole('button', { name: '版次', exact: true }).click()
    const history = page.getByRole('dialog', { name: '文件版次历史', exact: true }); await history.waitFor()
    const oldHistory = history.getByRole('row').filter({ has: page.locator('td:nth-child(4)').getByText(raw, { exact: true }) })
    const newHistory = history.getByRole('row').filter({ has: page.locator('td:nth-child(4)').getByText(nextRaw, { exact: true }) })
    await oldHistory.waitFor(); await newHistory.waitFor()
    await download(oldHistory.getByRole('button', { name: '原件', exact: true }), raw, bytes)
    await download(newHistory.getByRole('button', { name: '原件', exact: true }), nextRaw, nextBytes)
    await page.screenshot({ path: path.join(out, 'history-original-names.png'), fullPage: true, animations: 'disabled', mask: [page.locator('.avatar-container')] })
    await history.locator('.el-dialog__headerbtn').click()
    record('历史列表按版保存各自的系统名称和原始名称，历史原件下载正确')
    await page.screenshot({ path: path.join(out, 'catalog-file-names.png'), fullPage: true, animations: 'disabled', mask: [page.locator('.avatar-container')] })
    await page.goto(base + '/drilling/basic/files', { waitUntil: 'domcontentloaded' })
    await page.getByRole('tab', { name: '系统文件', exact: true }).click()
    await page.locator('input[placeholder="请输入文件名称"]').fill(renamed)
    row = page.getByRole('row').filter({ hasText: renamed }).first(); await row.waitFor()
    await download(row.getByRole('button', { name: '下载', exact: true }), nextRaw, nextBytes)
    record('系统文件列表共用显示名称，下载继续使用原名')
    await row.getByRole('button', { name: renamed, exact: true }).click()
    const detail = page.getByRole('dialog', { name: '文件详情', exact: true })
    await detail.getByText(nextRaw, { exact: true }).waitFor()
    await page.setViewportSize({ width: 430, height: 932 })
    await page.screenshot({ path: path.join(out, 'file-name-detail-mobile.png'), fullPage: true, animations: 'disabled', mask: [page.locator('.avatar-container')] })
    record('文件详情同时展示两种名称，窄屏可查看')
    await Promise.all(pending); assert.equal(errors.length, 0, errors.join('\n'))
    record('完整浏览器流程无脚本异常或接口错误')
    fs.writeFileSync(path.join(out, 'results.json'), JSON.stringify({ passed: true, count: checks.length, checks, errors }, null, 2))
  } finally { await browser.close() }
})().catch(error => {
  console.error(error)
  fs.writeFileSync(path.join(out, 'results.json'), JSON.stringify({ passed: false, checks, errors, error: String(error) }, null, 2))
  process.exitCode = 1
})
