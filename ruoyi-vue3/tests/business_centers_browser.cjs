/* Real UI acceptance. CENTERS_QA_CONFIG must refer to a disposable QA database. */
const fs=require('fs'),path=require('path')
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright')
const config=JSON.parse(fs.readFileSync(process.env.CENTERS_QA_CONFIG,'utf8'))
if(!/^drilling_ops_qa_centers_[0-9]+$/.test(config.database))throw Error('Disposable QA schema required')
const base=process.env.ACCESS_QA_FRONTEND||'http://127.0.0.1:15173'
const out=path.resolve(__dirname,'../../artifacts/business-centers');fs.mkdirSync(out,{recursive:true})
for(const name of ['browser-checks.json','browser-failure.json'])fs.rmSync(path.join(out,name),{force:true})
const checks=[],errors=[],failures=[]
function check(ok,name){checks.push({name,passed:Boolean(ok)});if(!ok)throw Error(name);console.log('PASS',name)}
;(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.ACCESS_QA_BROWSER,args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']})
 const ctx=await browser.newContext({viewport:{width:1600,height:1000}}),page=await ctx.newPage()
 page.on('pageerror',e=>errors.push(String(e)))
 page.on('response',r=>{if(r.status()>=400&&r.url().includes('/prod-api'))failures.push(`${r.status()} ${r.url()}`)})
 const login=await ctx.request.post(base+'/prod-api/login',{form:{username:'admin',password:config.adminPassword,rememberMe:'false'},headers:{'X-Requested-With':'XMLHttpRequest'}})
 check([0,200].includes((await login.json()).code),'administrator login')
 await ctx.addCookies([{name:'Admin-Token',value:'shiro-session',url:base}])
 await page.addInitScript(id=>localStorage.setItem('drilling.fieldId',id),String(config.fixture.fieldId))
 async function visit(key){await page.goto(base+'/drilling/centers/'+key);await page.locator('.center-search').waitFor();await page.waitForTimeout(450)}
 async function shot(name){await page.locator('.el-loading-mask:visible').first().waitFor({state:'hidden'});await page.screenshot({path:path.join(out,name+'.png'),fullPage:true,animations:'disabled'})}
 for(const key of ['alerts','history','quality','reports','connectors','versions']){
   await visit(key)
   check(await page.locator('.sidebar-container').getByText('钻井工程',{exact:true}).count()===1,key+' no duplicate drilling root')
   check(await page.locator('.center-search').isVisible(),key+' RuoYi query form')
   check(await page.getByRole('button',{name:'搜索',exact:true}).isVisible(),key+' query action')
   check(await page.locator('.center-toolbar').isVisible(),key+' batch toolbar')
   check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+3),key+' desktop fits viewport')
   const result=await ctx.request.get(base+'/prod-api/api/drilling/centers/'+key+'?fieldId='+config.fixture.fieldId+'&pageSize=1')
   check((await result.json()).rows.length<=1,key+' paged real data')
   await shot(key+'-desktop')
 }
 await visit('history')
 const sorted=page.waitForResponse(r=>r.url().includes('/centers/history?')&&r.url().includes('sort=record_id'))
 await page.getByRole('button',{name:'按 编号 排序',exact:true}).click()
 check((await sorted).status()===200,'table sort requests server ordering')
 await page.locator('.center-search input[placeholder="请输入查询内容"]').fill('不存在的验收关键词')
 const filtered=page.waitForResponse(r=>r.url().includes('/centers/history?')&&r.url().includes('keyword='))
 await page.getByRole('button',{name:'搜索',exact:true}).click()
 check((await (await filtered).json()).total===0,'query filters actual task rows')
 await page.getByText('暂无记录',{exact:true}).waitFor()
 const reset=page.waitForResponse(r=>r.url().includes('/centers/history?')&&!r.url().includes('keyword=%'))
 await page.getByRole('button',{name:'重置',exact:true}).click();await reset
 await page.getByRole('button',{name:'输入与结果',exact:true}).first().waitFor()
 const resized=page.waitForResponse(r=>r.url().includes('/centers/history?')&&r.url().includes('pageSize=10'))
 await page.locator('.el-pagination__sizes .el-select').click()
 await page.getByRole('option',{name:'10条/页',exact:true}).click()
 check((await resized).status()===200,'page-size selector requests bounded server page')
 const next=page.locator('.el-pagination .btn-next')
 if(await next.isEnabled()){
   const paged=page.waitForResponse(r=>r.url().includes('/centers/history?')&&r.url().includes('pageNum=2'))
   await next.click();check((await paged).status()===200,'pagination advances real task page')
   await visit('history')
 }
 await page.getByRole('button',{name:'输入与结果',exact:true}).first().click()
 await page.getByRole('dialog').waitFor()
 await page.getByText('基本信息',{exact:true}).waitFor()
 check(await page.getByText('基本信息',{exact:true}).isVisible(),'task details use structured records')
 await shot('history-detail')
 await page.getByRole('dialog').getByRole('button',{name:'关闭',exact:true}).click()
 await page.locator('.el-table__header-wrapper .el-checkbox').first().click();await page.waitForTimeout(150)
 check(await page.getByRole('button',{name:'导出所选',exact:true}).isEnabled(),'task batch selection enables export')
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'导出所选',exact:true}).click()
 check((await download).suggestedFilename()==='history.json','task batch export real download')
 await visit('quality')
 await page.getByRole('button',{name:'处理',exact:true}).first().click()
 check(await page.getByRole('dialog').getByText('处理说明',{exact:true}).isVisible(),'quality resolution requires a note')
 await shot('quality-resolution');await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click()
 await visit('reports')
 await page.getByRole('button',{name:'生成报告',exact:true}).click()
 check(await page.getByRole('dialog').getByLabel('报告名称').inputValue()==='井场钻井报告','report defaults supplied')
 await shot('report-create');await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click()
 await visit('connectors')
 await page.getByRole('button',{name:'新增',exact:true}).click()
 check(await page.getByRole('dialog').getByLabel('轮询间隔（s）').inputValue()==='30','connector defaults editable')
 await shot('connector-create');await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click()
 await visit('versions')
 await page.locator('.center-search .el-select').nth(0).click()
 await page.getByRole('option',{name:'测斜版本',exact:true}).click()
 await page.locator('.center-search .el-select').nth(2).click()
 await page.getByRole('option',{name:'正钻井',exact:true}).click()
 const surveys=page.waitForResponse(r=>r.url().includes('/centers/versions?')&&r.url().includes('type=SURVEY')&&r.url().includes('wellId='))
 await page.getByRole('button',{name:'搜索',exact:true}).click();await surveys
 await page.locator('.el-table__body-wrapper .el-checkbox').nth(1).waitFor()
 await page.locator('.el-table__body-wrapper .el-checkbox').nth(0).click();await page.locator('.el-table__body-wrapper .el-checkbox').nth(1).click();await page.waitForTimeout(150)
 check(await page.getByRole('button',{name:'版本比较',exact:true}).isEnabled(),'version comparison requires two selections')
 const compared=page.waitForResponse(r=>r.url().includes('/centers/versions/compare?'))
 await page.getByRole('button',{name:'版本比较',exact:true}).click()
 check((await (await compared).json()).differences.some(x=>x.field.includes('stations[')),'version UI compares real station content')
 await page.getByRole('dialog').locator('.el-table__row').first().waitFor()
 check(await page.getByRole('dialog').locator('.pagination-container').isVisible(),'version differences are paginated')
 await shot('version-comparison')
 await page.getByRole('dialog').getByRole('button',{name:'关闭',exact:true}).click()
 await page.getByRole('button',{name:'变更记录',exact:true}).click()
 check(await page.getByRole('dialog').getByRole('columnheader',{name:'变更内容',exact:true}).isVisible(),'version changes table')
 await shot('version-changes');await page.getByRole('dialog').locator('.el-dialog__headerbtn').click()
 await page.setViewportSize({width:390,height:844})
 for(const key of ['alerts','history','quality','reports','connectors','versions']){
   await visit(key)
   check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+3),key+' mobile fits viewport')
   check(await page.locator('.el-table__body-wrapper .el-table-fixed-column--right').count()===0,key+' mobile action column does not cover business data')
   await shot(key+'-mobile')
 }
 await page.setViewportSize({width:1600,height:1000})
 await page.evaluate(()=>localStorage.setItem('drilling-console-theme','light'))
 for(const key of ['alerts','history','quality','reports','connectors','versions']){
   await visit(key)
   check(!await page.locator('html').evaluate(el=>el.classList.contains('dark')),key+' light theme')
   check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+3),key+' light layout fits viewport')
   await shot(key+'-light')
 }
 const reader=await browser.newContext({viewport:{width:1440,height:900}})
 await reader.request.post(base+'/prod-api/login',{form:{username:config.reader.accountId,password:config.reader.password},headers:{'X-Requested-With':'XMLHttpRequest'}})
 await reader.addCookies([{name:'Admin-Token',value:'shiro-session',url:base}])
 const readerPage=await reader.newPage(),readerRequests=[]
 readerPage.on('response',r=>{if(r.status()>=400&&r.url().includes('/prod-api'))failures.push(`${r.status()} ${r.url()}`)})
 readerPage.on('request',r=>readerRequests.push(r.url()))
 readerPage.on('pageerror',e=>errors.push(String(e)))
 await readerPage.goto(base+'/drilling/centers/history')
 await readerPage.locator('.center-search').waitFor()
 await readerPage.getByRole('button',{name:'输入与结果',exact:true}).first().waitFor()
 check(await readerPage.locator('.drilling-field-search .el-select').innerText().then(x=>x.includes('CENTERS_')),'restricted role can select its authorized field')
 check(!readerRequests.some(url=>/\/fields\/\d+\/(files|configs)/.test(url)),'business centers do not require unrelated file/config permissions')
 check(await readerPage.getByRole('button',{name:'导出所选',exact:true}).count()===0,'read-only task role has no export action')
 await readerPage.locator('.el-loading-mask:visible').first().waitFor({state:'hidden'})
 await readerPage.screenshot({path:path.join(out,'history-readonly.png'),fullPage:true,animations:'disabled'})
 await reader.close()
 check(!errors.length,'no browser runtime errors: '+errors.join(';'))
 check(!failures.length,'no failed business API requests: '+failures.join(';'))
 fs.writeFileSync(path.join(out,'browser-checks.json'),JSON.stringify({checks,errors,failures},null,2))
 await browser.close();console.log('CHECKS',checks.length)
})().catch(e=>{console.error(e);fs.writeFileSync(path.join(out,'browser-failure.json'),JSON.stringify({checks,errors,failures},null,2));process.exit(1)})
